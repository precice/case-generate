import json
import hashlib
import shutil
import logging
from datetime import datetime
from pathlib import Path

logger = logging.getLogger(__name__)


class StateTracker:
    """
    The state tracker roughly works as follows:
    0) It maintains a file ".file-state.json" that maps file paths to their hashes to keep track of their contents.
    1) Look at the state file and compare the hashes of all tracked files (topology, precice-config, etc.)
    in the output directory with the hashes in the state file.
    2) If any file has changed, move it to a backup folder.
    3) After the generation is complete, look at the generated folders. If old folders (not newly generated) exist that
    contain files which are not tracked (i.e., custom files), move them to a backup folder.
    4) Save the new state file.
    """

    def __init__(self, output_root: Path):
        """
        Initialize the StateTracker.
        :param output_root: The root directory of the generated project.
        """
        self.output_root = output_root
        self.state_file = output_root / ".file-state.json"
        self.state = self._load_state()
        self._current_backup_dir: Path | None = None

    def _load_state(self) -> dict:
        """
        Load the previous state hashes if the file exists.
        :return: A dict mapping file paths to their hashes.
        """
        if self.state_file.exists():
            try:
                with open(self.state_file, "r") as f:
                    return json.load(f)
            except Exception as e:
                logger.warning(f"Could not read state file: {e}")
        return {}

    def _hash_file(self, filepath: Path) -> str:
        """
        Generate a SHA-256 hash of a file.
        :param filepath: The path to the file.
        :return: The SHA-256 hash of the file as a hex string.
        """
        hasher = hashlib.sha256()
        with open(filepath, "rb") as f:
            hasher.update(f.read())
        return hasher.hexdigest()

    def _get_backup_dir(self) -> Path:
        """
        Create the backup directory for the current run.
        :return: The path to the backup directory.
        """
        if self._current_backup_dir is None:
            timestamp: str = datetime.now().strftime('%Y%m%d_%H%M%S')
            self._current_backup_dir: Path = self.output_root / "backups" / f"{timestamp}"
            self._current_backup_dir.mkdir(parents=True, exist_ok=True)
        return self._current_backup_dir

    def backup_modified_files(self) -> None:
        """
        Check all previously generated files. If their current hash differs from the saved hash,
        back them up before the generator overwrites them.
        """
        for rel_path_str, saved_hash in self.state.items():
            filepath: Path = self.output_root / rel_path_str
            if filepath.exists() and filepath.is_file():
                current_hash: str = self._hash_file(filepath)

                if current_hash != saved_hash:
                    # The user modified this file manually
                    backup_dir: Path = self._get_backup_dir()
                    # Keep the relative folder structure inside the backup folder
                    backup_path: Path = backup_dir / rel_path_str
                    backup_path.parent.mkdir(parents=True, exist_ok=True)

                    # Move the file into the backup folder
                    shutil.move(str(filepath), str(backup_path))
                    logger.warning(f"File '{rel_path_str}' was manually modified. "
                                   f"Backed up to '{backup_path.relative_to(self.output_root)}'.")

    def cleanup_old_directories(self, valid_directories: set[Path]) -> None:
        """
        Delete (or backup) folders that were generated by the user, not modified,
        and are no longer used for the current run.
        :param valid_directories: A set of directories that are generated by the user in the current run.
        """
        # Identify all directories that were tracked previously
        tracked_dirs = set()
        for rel_path_str in self.state.keys():
            rel_path = Path(rel_path_str)
            if len(rel_path.parts) > 1:  # It's inside a subdirectory
                top_dir = self.output_root / rel_path.parts[0]
                tracked_dirs.add(top_dir.resolve())

        # Find old directories that are no longer used
        valid_resolved: set = {d.resolve() for d in valid_directories}
        old_directories: set = tracked_dirs - valid_resolved

        for directory in old_directories:
            if not directory.exists() or not directory.is_dir():
                continue

            # Check if the directory contains any custom files
            has_custom_files: bool = False
            for filepath in directory.rglob("*"):
                if filepath.is_file():
                    rel_path_str: str = str(filepath.relative_to(self.output_root.resolve()))
                    if rel_path_str not in self.state:
                        has_custom_files = True
                        break

            # If it does, move it to a backup folder
            if has_custom_files:
                backup_dir = self._get_backup_dir()
                backup_path = backup_dir / directory.name
                # Merge the directory into the backup folder to prevent duplicate files
                shutil.copytree(directory, backup_path, dirs_exist_ok=True)
                shutil.rmtree(directory)
                logger.warning(f"Directory '{directory.name}' contained custom files. "
                               f"Backed up to '{backup_path.relative_to(self.output_root)}'.")
            else:
                shutil.rmtree(directory)
                logger.debug(f"Cleaned up old not-modified directory '{directory.name}'.")

    def save_new_state(self) -> None:
        """
        Hash all generated configuration and utility files and save the state.
        """
        new_state: dict = {}
        # Track configurations and scripts (ignore preCICE logs, backups, etc.)
        tracked_extensions: set[str] = {".xml", ".json", ".sh", ".md"}

        for filepath in self.output_root.rglob("*"):
            if filepath.is_file():
                rel_path_str = str(filepath.relative_to(self.output_root))

                # Skip the state file itself and anything in a backup folder
                if rel_path_str == self.state_file.name or "backup_" in rel_path_str:
                    continue

                if filepath.suffix in tracked_extensions:
                    new_state[rel_path_str] = self._hash_file(filepath)

        # Write the new state invisibly
        with open(self.state_file, "w") as f:
            json.dump(new_state, f, indent=4)
        logger.debug("File generation state tracked and saved.")
